/* A set of animation frames: tilt steps 0..tilt-1, then special frames.
 * Built on demand in code (no constant pointer tables: on the glasses every
 * such table needs RAM plus a loader relocation). */
typedef struct {
    const uint8_t *data;       /* all frames, run-length encoded, back to back */
    const uint32_t *offsets;   /* frame i = data[offsets[i] .. offsets[i+1]) */
    uint16_t width;
    uint16_t height;
    uint8_t tilt;     /* number of rep-progress frames */
    uint8_t happy;    /* rep done (same pose as frame 0) */
    uint8_t sleepy;   /* paused  (same pose as frame 0) */
    uint8_t best;     /* new high score */
    uint8_t base;     /* SET_NONE, or the set this one is stored as a
                         difference from (glow-up tiers -> head, aura -> figure) */
} sprite_set_t;

#define SET_NONE   0xFFU
#define SET_HEAD   0U
#define SET_GLOW1  1U
#define SET_GLOW2  2U
#define SET_GLOW3  3U
#define SET_FIGURE 4U
#define SET_AURA   5U
#define SET_CAT    6U

#define HT HEAD_TILT_FRAMES
#define FT FIGURE_TILT_FRAMES
_Static_assert(HEAD_FRAMES == HT + 2U && FIGURE_FRAMES == FT + 2U &&
               AURA_FRAMES == FT + 2U, "sprites.h layout changed");

static void get_set(uint8_t id, sprite_set_t *out)
{
    out->base = (id == SET_GLOW1 || id == SET_GLOW2 || id == SET_GLOW3)
        ? SET_HEAD : id == SET_AURA ? SET_FIGURE : SET_NONE;
    switch (id) {
    case SET_GLOW1:  out->data = glow1_data;  out->offsets = glow1_offsets;  break;
    case SET_GLOW2:  out->data = glow2_data;  out->offsets = glow2_offsets;  break;
    case SET_GLOW3:  out->data = glow3_data;  out->offsets = glow3_offsets;  break;
    case SET_FIGURE: out->data = figure_data; out->offsets = figure_offsets; break;
    case SET_AURA:   out->data = aura_data;   out->offsets = aura_offsets;   break;
    case SET_CAT:    out->data = cat_data;    out->offsets = cat_offsets;    break;
    default:         out->data = head_data;   out->offsets = head_offsets;   break;
    }
    if (id == SET_CAT) {
        out->width = CAT_WIDTH; out->height = CAT_HEIGHT;
        out->tilt = 2; out->happy = 2; out->sleepy = 3; out->best = 4;
    } else if (id == SET_FIGURE || id == SET_AURA) {
        out->width = FIGURE_WIDTH; out->height = FIGURE_HEIGHT;
        out->tilt = FT; out->happy = FT; out->sleepy = FT + 1U; out->best = FT;
    } else {
        out->width = HEAD_WIDTH; out->height = HEAD_HEIGHT;
        out->tilt = HT; out->happy = HT; out->sleepy = HT + 1U; out->best = HT;
    }
}

