static void apply_layout(void)
{
    bool menu = G.state == ST_MENU;
    bool rolled = G.state == ST_ROLLED;
    bool workout = !menu && !rolled;
    bool ring = workout && G.style == STYLE_RING;
    bool chart = workout && G.style == STYLE_STONKS;
    bool live = workout && uses_live_figure();
    bool art = workout && !ring && !chart && !live;
    set_hidden(G.arc, !ring);
    set_hidden(G.image, !art);
    set_hidden(G.chart_axis, !chart);
    set_hidden(G.chart_line, !chart);
    set_hidden(G.chart_label, !chart);
    set_hidden(G.count_label, !workout);
    show_disco(rolled);
    set_hidden(G.popup_label, true);
    set_hidden(G.menu_box, !menu);
    if (!art) set_hidden(G.shadow, true);
    {
        uint8_t r;
        for (r = 0; r < MENU_COUNT; ++r) set_hidden(G.menu_rows[r], !menu);
    }
    set_hidden(G.status_label, false);
    show_figure(menu || rolled || live, live && G.style == STYLE_AURA);
    G.lvgl->obj_align(G.count_label, GM_PLUGIN_LVGL_ALIGN_CENTER,
                      ring ? 0 : 100, -40);
    if (art && G.image != 0)
        G.lvgl->obj_align(G.image, GM_PLUGIN_LVGL_ALIGN_CENTER, -100, -40);
    G.lvgl->label_set_text(G.title_label, menu ? "CHOOSE YOUR WORKOUT"
                                               : exercise_name(G.exercise));
    G.lvgl->label_set_text(G.hint_label, menu
        ? "Look up / down to choose   Press: start   Hold: exit"
        : rolled ? "Press: again   Double: menu   Hold: exit"
        : "Press: pause   Double: menu   Hold: exit");
    G.shown_set = SET_NONE;
    G.shown_frame = -1;
    G.shown_style = G.style;
    G.shown_menu = menu;
    G.shown_rolled = rolled;
}

