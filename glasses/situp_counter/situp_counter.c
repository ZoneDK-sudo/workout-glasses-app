static void refresh_menu(void)
{
    char text[72];
    int32_t t, pos;
    bool two_way = detector_of(G.exercise) == DET_SIGNED_PITCH;

    if (G.shown_hovered != G.hovered) show_hovered();
    G.lvgl->label_set_text(G.status_label, G.toast_ms > 0U ? G.toast : "");
    stats_text(text, sizeof(text));
    if (G.exercise == EX_ROLL)       /* totally a real workout */
        G.libc->snprintf(text, sizeof(text), "NEW: full-body rolling workout");
    else if (!G.cal[G.exercise].valid)
        G.libc->snprintf(text, sizeof(text), "First time: a quick 1-rep setup");
    G.lvgl->label_set_text(G.info_label, text);
    G.lvgl->label_set_text(G.stats_label, G.menu_settle_ms < MENU_SETTLE_MS
                           ? "Hold your head still..." : "");

    /* Preview: the figure loops through the hovered exercise. */
    t = (int32_t)(G.menu_anim_ms % 2000U);
    pos = t < 1000 ? t : 2000 - t;                      /* 0..1000..0 */
    if (two_way) pos = pos * 2 - 1000;                  /* -1000..1000 */
    if (G.exercise == EX_ROLL) draw_tumble(G.menu_anim_ms, FIG_X0_MENU);
    else draw_figure(G.exercise, pos, false, FIG_X0_MENU);
}

static void refresh_rolled(void)
{
    G.lvgl->label_set_text(G.status_label, G.toast_ms > 0U ? G.toast : "YOU GOT ROLLED!");
    G.lvgl->label_set_text(G.info_label, "Gotcha. Now go do some real sit-ups.");
    G.lvgl->label_set_text(G.stats_label, "");
    draw_dance(G.roll_ms, DANCE_X0, DANCE_Y0);
    draw_disco(G.roll_ms, DISCO_X, DISCO_Y);
}

static void refresh_workout(void)
{
    char text[72];
    uint32_t seconds = G.workout_ms / 1000U;
    int32_t pct = clamp32(abs32(G.progress), 0, 1000) / 10;

    G.libc->snprintf(text, sizeof(text), "%u", (unsigned int)G.count);
    G.lvgl->label_set_text(G.count_label, text);

    if (G.toast_ms > 0U)
        G.lvgl->label_set_text(G.status_label, G.toast);
    else if (G.paused)
        G.lvgl->label_set_text(G.status_label, "PAUSED - press to resume");
    else if (G.state == ST_POSITION)
        G.lvgl->label_set_text(G.status_label, position_prompt(G.exercise));
    else if (G.state == ST_CALIBRATING)
        G.lvgl->label_set_text(G.status_label, "Hold still...");
    else if (G.state == ST_SETUP) {
        uint8_t det = detector_of(G.exercise);
        const char *msg = setup_prompt(G.exercise);
        if (det == DET_PITCH && G.setup_a >= setup_minimum(G.exercise) * 10)
            msg = "Setup: now all the way back";
        else if (det == DET_SIGNED_PITCH && G.phase == 1U)
            msg = "Setup: now reach for the sky";
        G.lvgl->label_set_text(G.status_label, msg);
    } else if (G.new_best_flash_ms > 0U)
        G.lvgl->label_set_text(G.status_label, "NEW HIGH SCORE!");
    else if (G.style == STYLE_AURA) {
        G.libc->snprintf(text, sizeof(text), "Aura: %d", (int)G.aura);
        G.lvgl->label_set_text(G.status_label, text);
    } else
        G.lvgl->label_set_text(G.status_label, "Go!");

    if (G.state == ST_POSITION)
        G.libc->snprintf(text, sizeof(text), "Press to start anyway");
    else if (G.state == ST_SETUP)
        G.libc->snprintf(text, sizeof(text), "Measuring your movement...");
    else
        G.libc->snprintf(text, sizeof(text), "Rep %d%%    Time %02u:%02u", (int)pct,
                         (unsigned int)(seconds / 60U), (unsigned int)(seconds % 60U));
    G.lvgl->label_set_text(G.info_label, text);
    stats_text(text, sizeof(text));
    G.lvgl->label_set_text(G.stats_label, text);

    if (G.style == STYLE_RING) {
        G.celebrate_pending = false;
        G.lvgl->arc_set_range(G.arc, 0, 100);
        G.lvgl->arc_set_value(G.arc, (int16_t)pct);
    } else if (G.style == STYLE_STONKS) {
        if (G.celebrate_pending) {
            G.celebrate_pending = false;
            G.happy_ms = HAPPY_MS;
        }
        update_chart();
    } else if (uses_live_figure()) {
        if (G.celebrate_pending) {
            G.celebrate_pending = false;
            G.happy_ms = HAPPY_MS;
        }
        draw_figure(G.exercise, G.paused ? 0 : G.progress, G.style == STYLE_AURA, FIG_X0);
    } else {
        update_image();
    }

    /* Aura pop-up floats up from the figure and fades out. */
    if (G.style == STYLE_AURA && G.popup_ms > 0U && G.popup_label != 0) {
        int32_t rise = (int32_t)(POPUP_MS - G.popup_ms) * 40 / (int32_t)POPUP_MS;
        set_hidden(G.popup_label, false);
        G.lvgl->obj_align(G.popup_label, GM_PLUGIN_LVGL_ALIGN_CENTER,
                          -100, (gm_plugin_lvgl_coord_t)(-110 - rise));
    } else {
        set_hidden(G.popup_label, true);
    }
}

static void refresh_ui(void)
{
    bool menu = G.state == ST_MENU;
    bool rolled = G.state == ST_ROLLED;
    if (menu && G.shown_menu != menu) G.shown_hovered = 0xFFU;
    if (G.shown_style != G.style || G.shown_menu != menu ||
        G.shown_rolled != rolled ||
        G.fig_shown != (menu || rolled || (!rolled && uses_live_figure())))
        apply_layout();
    if (menu) refresh_menu();
    else if (rolled) refresh_rolled();
    else refresh_workout();
}

