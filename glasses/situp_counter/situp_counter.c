/* ------------------------------------------------------- frame drawing -- */

/* Decode one run-length encoded frame (see rle() in tools/make_sprites.py)
 * into a GRAY_4 indexed image: 16-entry palette, then packed pixels. */
static void decode_frame(uint8_t *out, const uint8_t *src, uint32_t size,
                         uint32_t pixel_count)
{
    uint8_t *pixels = out + 64;
    uint32_t pixel = 0U;
    uint32_t i = 0U;
    uint32_t k;

    for (k = 0U; k < 16U; ++k) {
        uint8_t v = (uint8_t)(k * 17U);
        out[k * 4U + 0U] = v;
        out[k * 4U + 1U] = v;
        out[k * 4U + 2U] = v;
        out[k * 4U + 3U] = k == 0U ? 0U : 255U;   /* 0 = transparent */
    }
    while (i < size && pixel < pixel_count) {
        uint8_t b = src[i++];
        uint8_t gray = (uint8_t)(b >> 4);
        uint32_t run = (uint32_t)(b & 0x0FU) + 1U;
        if ((b & 0x0FU) == 0x0FU) run = 16U + (i < size ? src[i++] : 0U);
        if (run > pixel_count - pixel) run = pixel_count - pixel;
        if ((pixel & 1U) != 0U && run != 0U) {          /* finish a byte */
            pixels[pixel >> 1] = (uint8_t)(pixels[pixel >> 1] | gray);
            ++pixel;
            --run;
        }
        if (run >= 2U) {                                  /* whole bytes */
            uint32_t bytes = run >> 1;
            G.libc->memset(pixels + (pixel >> 1),
                           (int)((gray << 4) | gray), bytes);
            pixel += bytes << 1;
            run &= 1U;
        }
        if (run != 0U) {                                  /* start a byte */
            pixels[pixel >> 1] = (uint8_t)(gray << 4);
            ++pixel;
        }
    }
    if (pixel < pixel_count)
        G.libc->memset(pixels + (pixel >> 1), 0, (pixel_count - pixel + 1U) >> 1);
}

/* Apply a run-length encoded difference: each run's value is XORed into
 * the pixels already decoded from the base frame (0 = unchanged). */
static void apply_delta(uint8_t *out, const uint8_t *src, uint32_t size,
                        uint32_t pixel_count)
{
    uint8_t *pixels = out + 64;
    uint32_t pixel = 0U;
    uint32_t i = 0U;
    while (i < size && pixel < pixel_count) {
        uint8_t b = src[i++];
        uint8_t x = (uint8_t)(b >> 4);
        uint32_t run = (uint32_t)(b & 0x0FU) + 1U;
        if ((b & 0x0FU) == 0x0FU) run = 16U + (i < size ? src[i++] : 0U);
        if (run > pixel_count - pixel) run = pixel_count - pixel;
        if (x == 0U) {                     /* unchanged: just skip ahead */
            pixel += run;
            continue;
        }
        while (run-- != 0U) {
            pixels[pixel >> 1] ^= (uint8_t)((pixel & 1U) ? x : (uint8_t)(x << 4));
            ++pixel;
        }
    }
}

static void decode_set_frame(uint8_t *buffer, const sprite_set_t *set,
                             uint8_t frame)
{
    uint32_t pixels = (uint32_t)set->width * set->height;
    uint32_t start = set->offsets[frame];
    uint32_t size = set->offsets[frame + 1U] - start;
    if (set->base != SET_NONE) {
        sprite_set_t base;
        uint32_t base_start;
        get_set(set->base, &base);
        base_start = base.offsets[frame];
        decode_frame(buffer, base.data + base_start,
                     base.offsets[frame + 1U] - base_start, pixels);
        apply_delta(buffer, set->data + start, size, pixels);
    } else {
        decode_frame(buffer, set->data + start, size, pixels);
    }
}

/* Which stored animation (if any) this style uses. Sit-ups have drawn art
 * for the figure styles; other exercises draw their figure live instead. */
static uint8_t current_set(void)
{
    switch (G.style) {
    case STYLE_HEAD:   return SET_HEAD;
    case STYLE_CAT:    return SET_CAT;
    case STYLE_FIGURE: return G.exercise == EX_SITUP ? SET_FIGURE : SET_NONE;
    case STYLE_AURA:   return G.exercise == EX_SITUP ? SET_AURA : SET_NONE;
    case STYLE_GLOWUP:
        return G.tier >= 3U ? SET_GLOW3 : G.tier == 2U ? SET_GLOW2
             : G.tier == 1U ? SET_GLOW1 : SET_HEAD;
    default:           return SET_NONE;
    }
}

static bool uses_live_figure(void)
{
    return G.state != ST_MENU && G.state != ST_ROLLED && G.exercise != EX_SITUP &&
           (G.style == STYLE_FIGURE || G.style == STYLE_AURA);
}

/* Upright resting pose for an exercise. The head art runs from leaning back
 * (frame 0) to curling forward; upright is 3/8 of the way. Sit-ups rest
 * leaning back (lying down); the cat always rests on frame 0. */
static int32_t rest_frame(const sprite_set_t *set)
{
    if (G.exercise == EX_SITUP || set->tilt < 5U) return 0;
    return ((int32_t)(set->tilt - 1U) * 375 + 500) / 1000;
}

/* Which frame the character should be heading for right now. */
static int32_t want_frame(const sprite_set_t *set)
{
    int32_t last = (int32_t)set->tilt - 1;
    int32_t rest = rest_frame(set);
    int32_t p = G.progress;
    bool cat = set->tilt < 5U;
    /* celebrations and the paused frame are drawn leaning back (frame 0) */
    if (G.happy_ms > 0U || G.celebrate_pending || G.paused) return 0;
    if (G.state < ST_SETUP) return rest;
    switch (G.exercise) {
    case EX_TOESKY:
        /* reach for the sky = lean back, touch the toes = curl down */
        if (cat) return p < -300 ? 1 : 0;           /* the cat looks up */
        if (p < 0) return rest + (p * rest - 500) / 1000;
        return rest + (p * (last - rest) + 500) / 1000;
    case EX_JACKS:
        /* effort face when the arms are up */
        if (cat) return G.anim_pos > 500 ? 1 : 0;
        return clamp32(rest + (G.anim_pos * 2 + 500) / 1000, 0, last);
    default:   /* sit-ups: follow how far through the rep you are */
        return clamp32((abs32(p) * last + 500) / 1000, 0, last);
    }
}

/* Glide one step per update (two when far behind) toward the wanted frame,
 * so it never jumps; the celebration shows once it has glided to frame 0. */
static int16_t glide_tilt(const sprite_set_t *set)
{
    int32_t target = want_frame(set);
    int32_t gap;
    if (G.shown_tilt > (int16_t)(set->tilt - 1U)) G.shown_tilt = (int16_t)(set->tilt - 1U);
    gap = target - G.shown_tilt;
    if (gap > 0) G.shown_tilt += (int16_t)(gap > 3 ? 2 : 1);
    else if (gap < 0) G.shown_tilt -= (int16_t)(gap < -3 ? 2 : 1);
    if (G.shown_tilt == 0 && G.celebrate_pending) {
        G.celebrate_pending = false;
        G.happy_ms = HAPPY_MS;
    }
    return G.shown_tilt;
}

static uint8_t pick_frame(const sprite_set_t *set)
{
    int16_t tilt = glide_tilt(set);
    if (tilt != 0) return (uint8_t)tilt;
    if (G.happy_ms > 0U)
        return G.new_best_flash_ms > 0U ? set->best : set->happy;
    if (G.paused) return set->sleepy;
    return 0U;
}

/* Jumping jacks: each jump is a hop (up and back down while the arms move),
 * pixels above the resting spot. */
static int32_t hop_height(void)
{
    int32_t half;
    if (G.exercise != EX_JACKS || G.state != ST_COUNTING || G.paused) return 0;
    half = G.anim_pos < 1000 - G.anim_pos ? G.anim_pos : 1000 - G.anim_pos;  /* 0..500 */
    return half * HOP_PX / 500;
}

/* Small shadow on the floor under a hopping character: narrower when higher. */
static void update_shadow(const sprite_set_t *set, int32_t hop)
{
    gm_plugin_lvgl_point_t *pts = G.shadow_points[G.shadow_buffer];
    int32_t half = 34 - hop * 18 / HOP_PX;
    int32_t y = 175 - 40 + (int32_t)set->height / 2 + 4;
    pts[0].x = (gm_plugin_lvgl_coord_t)(200 - half);
    pts[0].y = (gm_plugin_lvgl_coord_t)y;
    pts[1].x = (gm_plugin_lvgl_coord_t)(200 + half);
    pts[1].y = (gm_plugin_lvgl_coord_t)y;
    G.lvgl->line_set_points(G.shadow, pts, 2);
    G.shadow_buffer ^= 1U;
}

static void update_image(void)
{
    uint8_t id = current_set();
    sprite_set_t set;
    sprite_set_t shown;
    gm_plugin_lvgl_image_dsc_t dsc;
    uint8_t *buffer;
    uint8_t frame;

    if (G.image == 0 || id == SET_NONE) return;
    get_set(id, &set);
    frame = pick_frame(&set);
    {
        int32_t hop = hop_height();
        bool jacks = G.exercise == EX_JACKS && G.state == ST_COUNTING;
        set_hidden(G.shadow, !jacks);
        if (jacks) update_shadow(&set, hop);
        if (hop != G.shown_hop) {
            G.lvgl->obj_align(G.image, GM_PLUGIN_LVGL_ALIGN_CENTER, -100,
                              (gm_plugin_lvgl_coord_t)(-40 - hop));
            G.shown_hop = (int16_t)hop;
        }
    }
    if (id == G.shown_set && (int16_t)frame == G.shown_frame) return;

    buffer = G.pixels[G.next_buffer];
    decode_set_frame(buffer, &set, frame);
    dsc.struct_size = (uint16_t)sizeof(dsc);
    dsc.width = set.width;
    dsc.height = set.height;
    dsc.format = GM_PLUGIN_LVGL_IMAGE_INDEXED_4BIT;
    dsc.reserved = 0U;
    dsc.data = buffer;
    dsc.data_size = 64U + ((uint32_t)set.width / 2U) * set.height;
    if (G.lvgl->image_set_source(G.image, &dsc) != GM_PLUGIN_OK) return;
    G.next_buffer ^= 1U;
    if (G.shown_set == SET_NONE) {
        G.lvgl->obj_align(G.image, GM_PLUGIN_LVGL_ALIGN_CENTER, -100, (gm_plugin_lvgl_coord_t)(-40 - G.shown_hop));
    } else {
        get_set(G.shown_set, &shown);
        if (shown.width != set.width || shown.height != set.height)
            G.lvgl->obj_align(G.image, GM_PLUGIN_LVGL_ALIGN_CENTER, -100, (gm_plugin_lvgl_coord_t)(-40 - G.shown_hop));
    }
    G.shown_set = id;
    G.shown_frame = (int16_t)frame;
}

