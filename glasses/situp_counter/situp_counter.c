/* The Roll prank: straight to the dance party, and cue the phone's sting. */
static void enter_rolled(void)
{
    G.state = ST_ROLLED;
    G.paused = false;
    G.roll_ms = 0U;
    send_event(EV_ROLLED, 0U);
    G.host->log("workout: rolled");
}

static void start_workout(void)
{
    if (G.exercise == EX_ROLL) { enter_rolled(); return; }
    new_session();
    G.paused = false;
    G.sensitivity = 0;
    enter_position();
}

/* Menu: the row you were on sits under "straight ahead"; tilting the head
 * up or down by MENU_STEP_DEG moves one row. First learn straight ahead. */
static void recenter_menu(void)
{
    G.menu_settle_ms = 0U;
    G.menu_sum10 = 0;
    G.menu_start_row = G.hovered;
}

static void enter_menu(void)
{
    G.state = ST_MENU;
    G.paused = false;
    G.setup_forced = false;
    G.progress = 0;
    G.menu_anim_ms = 0U;
    G.hovered = menu_row_of(G.exercise);
    G.menu_stats_sent = true;
    recenter_menu();
}

static void back_to_menu(void)
{
    send_session();
    enter_menu();
}

static void hover_row(uint8_t row)
{
    if (row >= MENU_COUNT || row == G.hovered) return;
    G.hovered = row;
    G.exercise = menu_exercise(row);
    G.menu_anim_ms = 0U;
    clear_stats();
    G.menu_stats_ms = 0U;          /* ask the phone once the hover settles */
    G.menu_stats_sent = false;
}

static void update_menu_pointer(void)
{
    int32_t pos, row;
    if (G.menu_settle_ms < MENU_SETTLE_MS) {
        G.menu_sum10 += G.pitch_f10;
        G.menu_settle_ms += SLOW_TICK_MS;
        if (G.menu_settle_ms >= MENU_SETTLE_MS)
            G.menu_center10 = G.menu_sum10 / (int32_t)(MENU_SETTLE_MS / SLOW_TICK_MS);
        return;
    }
    /* position in rows x100; looking up (positive tilt) moves up the list */
    pos = (int32_t)G.menu_start_row * 100 -
          (G.pitch_f10 - G.menu_center10) * 100 / (MENU_STEP_DEG * 10);
    pos = clamp32(pos, 0, (int32_t)(MENU_COUNT - 1U) * 100);
    if (abs32(pos - (int32_t)G.hovered * 100) > MENU_HYSTERESIS) {
        row = (pos + 50) / 100;
        hover_row((uint8_t)row);
    }
    if (!G.menu_stats_sent) {
        G.menu_stats_ms += SLOW_TICK_MS;
        if (G.menu_stats_ms >= MENU_STATS_DELAY_MS) {
            G.menu_stats_sent = true;
            send_exercise();   /* the phone answers with this exercise's stats */
        }
    }
}

/* --------------------------------------------------------- rep counted -- */

static void on_rep(void)
{
    /* One sound per rep: a tier-up beats a new best, which beats a plain rep. */
    uint8_t event = EV_REP;
    uint32_t value;
    uint8_t tier;

    G.count++;
    value = G.count;
    G.since_rep_ms = 0;
    /* jumping jacks come fast: the character hops every jump and grins on
     * every 10th rep (and new bests, below) instead of every rep */
    G.celebrate_pending = G.exercise != EX_JACKS || G.count % JACKS_CHEER_EVERY == 0U;
    G.aura += 100;
    close_price();
    G.host->log("workout: %s rep %u", exercise_name(G.exercise), (unsigned int)G.count);

    if (G.have_stats && G.best > 0U && G.count == (uint32_t)G.best + 1U &&
        !G.new_best_shown) {
        G.new_best_shown = true;
        G.new_best_flash_ms = NEW_BEST_FLASH_MS;
        G.celebrate_pending = true;
        event = EV_BEST;
    }
    if (G.style == STYLE_AURA) {
        G.lvgl->label_set_text(G.popup_label, "+100 AURA");
        G.popup_ms = POPUP_MS;
    }
    tier = G.count >= 50U ? 3U : G.count >= 25U ? 2U : G.count >= 10U ? 1U : 0U;
    if (tier != G.tier) {
        G.tier = tier;
        if (G.style == STYLE_GLOWUP) {
            show_toast(tier_name(tier));
            event = EV_TIER;
            value = tier;
        }
    }
    send_event(event, value);
    send_session();
}

static void finish_setup(uint16_t a, uint16_t b, uint8_t c, uint32_t reps)
{
    char text[40];
    G.cal[G.exercise].a = a;
    G.cal[G.exercise].b = b;
    G.cal[G.exercise].c = c;
    G.cal[G.exercise].valid = 1U;
    G.setup_forced = false;
    send_cal(G.exercise);
    G.host->log("workout: %s setup a=%u b=%u c=%u", exercise_name(G.exercise),
                (unsigned int)a, (unsigned int)b, (unsigned int)c);
    G.libc->snprintf(text, sizeof(text), "Setup done!");
    show_toast(text);
    G.announce_ready = false;      /* the rep sound is the "go" */
    enter_ready();
    while (reps-- != 0U) on_rep(); /* the setup reps were real reps */
}

/* ------------------------------------------------------ fast detectors -- */

/* Every IMU read: acceleration and rotation, which change quickly. */
static void process_fast(const gm_plugin_imu_sample_t *s, uint32_t dt)
{
    uint32_t sq = 0U;
    uint32_t mag;
    int32_t mg = 0;
    uint8_t det = detector_of(G.exercise);
    cal_t c = G.cal[G.exercise];
    uint8_t i;

    for (i = 0; i < 3; ++i) {
        int32_t v = s->accel_raw[i];
        sq += (uint32_t)(v * v);
    }
    mag = isqrt32(sq);

    if (G.state == ST_CALIBRATING) {
        G.calib_mag_sum += (int32_t)mag;
        G.calib_fast++;
        return;
    }
    if (G.state != ST_SETUP && G.state != ST_COUNTING) return;
    if (!c.valid) default_cal(G.exercise, &c);   /* setup skipped */

    if (G.g_mag > 0) mg = ((int32_t)mag - G.g_mag) * 1000 / G.g_mag;
    G.accel_mg += (mg - G.accel_mg) / 4;
    (void)dt;

    if (det == DET_PEAKS) {
        bool rising = !G.in_peak && G.since_peak_ms >= 220U;
        if (G.state == ST_SETUP) {
            if (rising && mg >= setup_minimum(EX_JACKS)) {
                G.in_peak = true;
                G.since_peak_ms = 0U;
                G.setup_quiet_ms = 0U;
                if (G.setup_peaks < 24U) G.setup_peak_list[G.setup_peaks] = (uint16_t)clamp32(mg, 0, 65535);
                G.setup_peaks++;
                G.anim_target = G.anim_target ? 0 : 1000;
            } else if (G.in_peak && G.setup_peaks <= 24U && mg > G.setup_peak_list[G.setup_peaks - 1U]) {
                G.setup_peak_list[G.setup_peaks - 1U] = (uint16_t)clamp32(mg, 0, 65535);
            }
            if (G.in_peak && mg < setup_minimum(EX_JACKS) / 2) G.in_peak = false;
            return;
        } else {
            int32_t at = (int32_t)c.a * (rep_percent() - 5) / 100;
            uint32_t per = c.c ? c.c : 2U;
            uint32_t half = per / 2U ? per / 2U : 1U;
            if (rising && mg >= at) {
                G.in_peak = true;
                G.since_peak_ms = 0U;
                G.peaks++;
                G.anim_target = (((G.peaks - 1U) / half) % 2U) ? 0 : 1000;
                if (G.peaks % per == 0U) on_rep();
            }
            if (G.in_peak && mg < at / 2) G.in_peak = false;
        }
    }
}

/* ------------------------------------------------------ slow detectors -- */

/* Every 50 ms: tilt-based exercises, setups and the overall flow. */
static void process_slow(const gm_plugin_imu_sample_t *s)
{
    int32_t pitch10 = (int32_t)s->pitch_degrees * 10;
    uint8_t det = detector_of(G.exercise);
    cal_t c = G.cal[G.exercise];
    int32_t pct = rep_percent();
    int32_t d10, dev10;

    if (!G.have_pitch) { G.pitch_f10 = pitch10; G.have_pitch = true; }
    else G.pitch_f10 += (pitch10 - G.pitch_f10) / 3;

    if (G.state == ST_MENU) {
        update_menu_pointer();
        return;
    }
    if (G.state == ST_POSITION) {
        int32_t tilt = abs32(G.pitch_f10);
        bool there = position_of(G.exercise) == POS_LYING
            ? tilt >= LYING_MIN_DEG * 10 : tilt <= STANDING_MAX_DEG * 10;
        G.position_ms = there ? G.position_ms + SLOW_TICK_MS : 0U;
        if (G.position_ms >= POSITION_HOLD_MS) enter_calibrating();
        return;
    }
    if (G.state == ST_CALIBRATING) {
        G.calib_pitch_sum += G.pitch_f10;
        G.calib_samples++;
        G.calib_ms += SLOW_TICK_MS;
        if (G.calib_ms >= CALIBRATION_MS) {
            G.base_pitch10 = G.calib_pitch_sum / (int32_t)G.calib_samples;
            if (G.calib_fast > 0U)              /* gravity at rest */
                G.g_mag = G.calib_mag_sum / (int32_t)G.calib_fast;
            G.accel_mg = 0;
            if (G.cal[G.exercise].valid && !G.setup_forced) enter_ready();
            else enter_setup();
        }
        return;
    }
    if (G.state != ST_SETUP && G.state != ST_COUNTING) return;
    if (!c.valid) default_cal(G.exercise, &c);

    d10 = G.pitch_f10 - G.base_pitch10;
    dev10 = abs32(d10);

    switch (det) {
    case DET_PITCH: {
        int32_t range10 = (int32_t)c.a * 10;
        if (G.state == ST_SETUP) {
            int32_t min10 = setup_minimum(G.exercise) * 10;
            if (dev10 > G.setup_a) G.setup_a = dev10;
            G.progress = (int16_t)clamp32(dev10 * 1000 / (G.setup_a > min10 * 2 ? G.setup_a : min10 * 2), 0, 1000);
            if (G.setup_a >= min10 && dev10 <= G.setup_a / 4)
                finish_setup((uint16_t)clamp32((G.setup_a + 5) / 10, 1, 255), 0U, 0U, 1U);
            break;
        }
        {
            int32_t at = range10 * pct / 100;
            int32_t back = range10 * RETURN_PERCENT / 100;
            if (back < 15) back = 15;
            if (back > at / 2) back = at / 2;
            G.progress = (int16_t)clamp32(dev10 * 1000 / (range10 ? range10 : 1), 0, 1000);
            if (G.phase == 0U && dev10 >= at) G.phase = 1U;
            else if (G.phase == 1U && dev10 <= back && G.since_rep_ms >= MIN_REP_MS) {
                G.phase = 0U;
                on_rep();
            }
        }
        break;
    }
    case DET_SIGNED_PITCH: {
        if (G.state == ST_SETUP) {
            /* toes first: the first big tilt tells us which way is "down" */
            if (G.setup_sign == 0 && dev10 >= setup_minimum(EX_TOESKY) * 10)
                G.setup_sign = d10 > 0 ? 1 : -1;
            if (G.setup_sign != 0) {
                int32_t sd = d10 * G.setup_sign;
                if (G.phase == 0U) {
                    if (sd > G.setup_a) G.setup_a = sd;
                    G.progress = (int16_t)clamp32(sd * 1000 / (G.setup_a > 1 ? G.setup_a : 1), 0, 1000);
                    if (sd <= G.setup_a / 2) G.phase = 1U;
                } else {
                    if (-sd > G.setup_b) G.setup_b = -sd;
                    G.progress = (int16_t)clamp32(sd * 1000 / (G.setup_b > 300 ? G.setup_b : 300), -1000, 1000);
                    if (G.setup_b >= 80 && -sd <= G.setup_b / 4)
                        finish_setup((uint16_t)clamp32(G.setup_a / 10, 1, 255),
                                     (uint16_t)clamp32(G.setup_b / 10, 1, 255),
                                     G.setup_sign < 0 ? 1U : 0U, 1U);
                }
            }
            break;
        }
        {
            int32_t sd = c.c ? -d10 : d10;          /* + toward the toes */
            int32_t toe10 = (int32_t)c.a * 10, sky10 = (int32_t)c.b * 10;
            G.progress = (int16_t)clamp32(sd >= 0 ? sd * 1000 / toe10 : sd * 1000 / sky10, -1000, 1000);
            if (G.phase == 0U && sd >= toe10 * pct / 100) G.phase = 1U;
            else if (G.phase == 1U && -sd >= sky10 * pct / 100 && G.since_rep_ms >= MIN_REP_MS) {
                G.phase = 0U;
                on_rep();
            }
        }
        break;
    }
    case DET_PEAKS: {
        /* the figure glides toward where the motion says you are */
        int32_t step = 1000 * (int32_t)SLOW_TICK_MS / 250;
        if (G.anim_pos < G.anim_target) G.anim_pos = (int16_t)clamp32(G.anim_pos + step, 0, G.anim_target);
        else if (G.anim_pos > G.anim_target) G.anim_pos = (int16_t)clamp32(G.anim_pos - step, G.anim_target, 1000);
        G.progress = G.anim_pos;
        if (G.state == ST_SETUP) {
            if (G.setup_peaks >= 3U && G.since_peak_ms >= 1500U) {
                /* learn how many bumps one jack makes at the counting level */
                uint32_t i, n = G.setup_peaks < 24U ? G.setup_peaks : 24U, hits = 0U;
                int32_t top = 0, at;
                for (i = 0; i < n; ++i) if (G.setup_peak_list[i] > top) top = G.setup_peak_list[i];
                at = top * (REP_PERCENT - 5) / 100;
                for (i = 0; i < n; ++i) if (G.setup_peak_list[i] >= at) hits++;
                finish_setup((uint16_t)clamp32(top, 1, 65535), 0U,
                             (uint8_t)clamp32(((int32_t)hits + 1) / 3, 1, 4), 3U);
            }
        }
        break;
    }
    default:
        break;
    }
}
/* Borrow the two frame buffers. Without them the picture styles are
 * unavailable for this run and the ring / stonks styles still work. */
static void alloc_pixels(void)
{
    uint8_t i;
    G.images_ok = false;
    G.pixels[0] = G.pixels[1] = 0;
    if (!G.images_cap) return;
    for (i = 0U; i < 2U; ++i) {
        G.pixels[i] = G.host->alloc(FRAME_BYTES);
        /* LVGL reads the palette as 32-bit words: the buffer must be aligned. */
        if (G.pixels[i] == 0 || ((uintptr_t)G.pixels[i] & 3U) != 0U) return;
    }
    G.images_ok = true;
}

static void free_pixels(void)
{
    uint8_t i;
    for (i = 0U; i < 2U; ++i) {
        if (G.pixels[i] != 0) G.host->free(G.pixels[i]);
        G.pixels[i] = 0;
    }
    G.images_ok = false;
}

static gm_plugin_result_t plugin_start(void *context)
{
    gm_plugin_result_t result;
    uint8_t i;
    (void)context;

    result = example_call_ui_start(&G.call_ui);
    if (result != GM_PLUGIN_OK) return result;

    G.exercise = EX_SITUP;
    G.paused = false;
    G.sensitivity = 0;
    G.have_pitch = false;
    G.slow_ms = SLOW_TICK_MS;
    G.since_rep_ms = MIN_REP_MS;
    G.log_ms = 0;
    G.resend_ms = 0;
    G.style = DEFAULT_STYLE;
    G.style_pending = false;
    G.happy_ms = 0;
    G.celebrate_pending = false;
    G.shown_tilt = 0;
    G.toast_ms = 0;
    G.popup_ms = 0;
    G.setup_forced = false;
    G.g_mag = 0;
    for (i = 0; i < EX_COUNT; ++i) G.cal[i].valid = 0U;
    clear_stats();
    new_session();
    enter_menu();
    alloc_pixels();

    if (!create_ui()) {
        free_pixels();
        example_call_ui_stop(&G.call_ui);
        return GM_PLUGIN_ENOMEM;
    }
    result = G.host->imu_enable(GM_PLUGIN_IMU_ENABLE_RAW);
    if (result != GM_PLUGIN_OK) {
        G.lvgl->obj_clean(G.lvgl->root_get());
        free_pixels();
        example_call_ui_stop(&G.call_ui);
        return result;
    }
    send_hello();
    refresh_ui();
    return GM_PLUGIN_OK;
}

static void plugin_loop(void *context, uint32_t elapsed_ms)
{
    gm_plugin_imu_sample_t sample;
    bool have_sample;
    (void)context;
    if (elapsed_ms > 1000U) elapsed_ms = 1000U;

    G.slow_ms = add_capped(G.slow_ms, elapsed_ms, SLOW_TICK_MS);
    G.log_ms = add_capped(G.log_ms, elapsed_ms, LOG_INTERVAL_MS);
    G.resend_ms = add_capped(G.resend_ms, elapsed_ms, RESEND_MS);
    G.since_peak_ms = add_capped(G.since_peak_ms, elapsed_ms, 60000U);
    G.new_best_flash_ms = count_down(G.new_best_flash_ms, elapsed_ms);
    G.happy_ms = count_down(G.happy_ms, elapsed_ms);
    G.toast_ms = count_down(G.toast_ms, elapsed_ms);
    G.popup_ms = count_down(G.popup_ms, elapsed_ms);
    if (G.state == ST_MENU) G.menu_anim_ms += elapsed_ms;
    if (G.state == ST_ROLLED) G.roll_ms += elapsed_ms;
    if (!G.paused) {
        G.since_rep_ms = add_capped(G.since_rep_ms, elapsed_ms, 60000U);
        if (G.state == ST_COUNTING || G.state == ST_SETUP)
            G.workout_ms = add_capped(G.workout_ms, elapsed_ms, UINT32_C(99) * 60000U);
    }

    /* Keep resending until the phone confirms it stored this session. */
    if (G.resend_ms >= RESEND_MS && !session_synced()) send_session();

    have_sample = !G.paused && G.host->imu_read(&sample) == GM_PLUGIN_OK;
    if (have_sample) process_fast(&sample, elapsed_ms);

    if (G.slow_ms < SLOW_TICK_MS) return;
    G.slow_ms = 0;
    if (have_sample) {
        process_slow(&sample);
        if (G.log_ms >= LOG_INTERVAL_MS && G.state != ST_MENU) {
            G.log_ms = 0;
            G.host->log("workout: pitch=%d accel=%dmg progress=%d count=%u",
                        (int)sample.pitch_degrees, (int)G.accel_mg,
                        (int)G.progress, (unsigned int)G.count);
        }
    }
    if (!G.call_ui.active) refresh_ui();
}

static void toggle_pause(void)
{
    G.paused = !G.paused;
    if (G.paused) {
        send_session();
        send_event(EV_PAUSE, G.count);
        if (G.style == STYLE_AURA && G.count > 0U) {
            G.aura -= 1000;
            G.lvgl->label_set_text(G.popup_label, "-1000 AURA");
            G.popup_ms = POPUP_MS;
        }
    } else {
        send_event(EV_RESUME, G.count);
        enter_position();   /* back in position (e.g. lying down) first */
    }
}

static bool handle_button(gm_plugin_button_t button,
                          gm_plugin_button_action_t action)
{
    if (action == GM_PLUGIN_BUTTON_ACTION_LONG ||
        action == GM_PLUGIN_BUTTON_ACTION_VERY_LONG) {
        send_session(); /* last chance to hand the reps to the phone */
        G.host->app_exit();
        return true;
    }
    if (action == GM_PLUGIN_BUTTON_ACTION_SINGLE) {
        if (G.state == ST_MENU) {
            start_workout();
        } else if (G.state == ST_ROLLED) {     /* play it again */
            G.roll_ms = 0U;
            send_event(EV_ROLLED, 0U);
            show_toast("STILL ROLLED");
        } else if (G.state == ST_POSITION && !G.paused) {
            enter_calibrating();               /* start anyway */
        } else if (G.state == ST_SETUP) {      /* skip setup: use defaults */
            G.setup_forced = false;
            enter_ready();
            show_toast("Setup skipped");
        } else {
            toggle_pause();
        }
        return true;
    }
    if (action == GM_PLUGIN_BUTTON_ACTION_DOUBLE) {
        if (G.state == ST_MENU) {           /* re-centre the head pointer */
            recenter_menu();
            show_toast("Re-centred");
        } else {
            back_to_menu();
        }
        return true;
    }
    if (action == GM_PLUGIN_BUTTON_ACTION_TRIGGER) {
        if (button == GM_PLUGIN_BUTTON_LEFT || button == GM_PLUGIN_BUTTON_RIGHT) {
            int32_t dir = button == GM_PLUGIN_BUTTON_RIGHT ? 1 : -1;
            if (G.state == ST_MENU) {
                hover_row((uint8_t)clamp32((int32_t)G.hovered + dir, 0, MENU_COUNT - 1));
                recenter_menu();
            } else if (G.state == ST_ROLLED) {
                return false;
            } else {
                uint8_t style = G.style;
                char text[40];
                do {   /* skip styles this firmware can't draw */
                    style = (uint8_t)((style + STYLE_COUNT + dir) % STYLE_COUNT);
                } while (usable_style(style) != style);
                select_style(style);
                G.style_pending = G.bt_available && G.have_stats;
                G.libc->snprintf(text, sizeof(text), "< %s >", style_name(G.style));
                show_toast(text);
                send_style();
            }
            return true;
        }
        if (G.state == ST_MENU && (button == GM_PLUGIN_BUTTON_UP ||
                                   button == GM_PLUGIN_BUTTON_DOWN)) {
            int32_t dir = button == GM_PLUGIN_BUTTON_DOWN ? 1 : -1;
            hover_row((uint8_t)clamp32((int32_t)G.hovered + dir, 0, MENU_COUNT - 1));
            recenter_menu();                 /* head pointer follows from here */
            return true;
        }
        if (G.state == ST_ROLLED) return false;
        if (G.state != ST_MENU && (button == GM_PLUGIN_BUTTON_UP ||
                                   button == GM_PLUGIN_BUTTON_DOWN)) {
            char text[40];
            G.sensitivity = clamp32(G.sensitivity +
                (button == GM_PLUGIN_BUTTON_UP ? 5 : -5), -30, 30);
            G.libc->snprintf(text, sizeof(text), "Rep counts at %d%%", (int)rep_percent());
            show_toast(text);
            return true;
        }
    }
    return false;
}

static bool handle_phone(const uint8_t *d, uint32_t length)
{
    if (d == 0 || length < 2U || d[0] != PROTO) return false;
    if (d[1] == MSG_STATS) return handle_stats(d, length);
    if (d[1] == MSG_CALS) return handle_cals(d, length);
    if (d[1] == MSG_SETUP && length >= 3U && d[2] < EX_COUNT && d[2] != EX_ROLL &&
        menu_exercise(menu_row_of(d[2])) == d[2]) {    /* not a retired one */
        /* "Recalibrate" on the phone: run that exercise's setup again */
        if (G.state != ST_MENU) send_session();
        if (d[2] != G.exercise) {
            G.exercise = d[2];
            G.hovered = menu_row_of(d[2]);
            clear_stats();
            send_exercise();
        }
        start_workout();
        G.setup_forced = true;
        return true;
    }
    return false;
}

static bool plugin_event(void *context, const gm_plugin_event_t *event)
{
    bool handled = false;
    (void)context;
    if (event == 0) return false;

    if (event->type == GM_PLUGIN_EVENT_BUTTON) {
        handled = handle_button(event->data.button.button,
                                event->data.button.action);
    } else if (event->type == GM_PLUGIN_EVENT_BT_MESSAGE &&
               event->data.bt.channel == PHONE_TO_GLASSES) {
        handled = handle_phone(event->data.bt.data, event->data.bt.length);
    } else if (event->type == GM_PLUGIN_EVENT_CONNECTION) {
        if (event->data.connection.connected) {
            send_hello();
            send_session();
        }
        handled = true;
    }
    if (handled && !G.call_ui.active && G.count_label != 0) refresh_ui();
    return handled;
}

static void plugin_stop(void *context)
{
    uint8_t i;
    (void)context;
    send_session();
    example_call_ui_stop(&G.call_ui);
    (void)G.host->imu_enable(GM_PLUGIN_IMU_ENABLE_NONE);
    G.lvgl->obj_clean(G.lvgl->root_get());   /* delete the image first... */
    free_pixels();                              /* ...then its buffers */
    G.arc = G.count_label = G.status_label = 0;
    G.info_label = G.stats_label = G.image = G.popup_label = 0;
    G.title_label = G.hint_label = 0;
    G.chart_axis = G.chart_line = G.chart_label = 0;
    G.menu_box = G.shadow = 0;
    for (i = 0; i < ROLL_LINES; ++i) G.disco[i] = 0;
    for (i = 0; i < MENU_COUNT; ++i) G.menu_rows[i] = 0;
    for (i = 0; i < FIG_LINES; ++i) G.fig[i] = G.fig_glow[i] = 0;
}

gm_plugin_result_t gm_plugin_entry(const gm_plugin_host_api_t *host,
                                   gm_plugin_descriptor_t *plugin)
{
    const gm_plugin_capabilities_t required = GM_PLUGIN_CAP_BUTTON |
                                               GM_PLUGIN_CAP_IMU_RAW;
    if (host == 0 || plugin == 0 || host->imu_enable == 0 ||
        host->imu_read == 0 || host->log == 0 || host->app_exit == 0 ||
        host->graphics.lvgl == 0 ||
        !GM_PLUGIN_VERSION_COMPATIBLE(host->abi_version,
                                      GM_PLUGIN_ABI_MIN_VERSION) ||
        host->struct_size < GM_PLUGIN_HOST_API_MIN_SIZE ||
        plugin->struct_size < GM_PLUGIN_DESCRIPTOR_MIN_SIZE ||
        (host->capabilities & required) != required)
        return GM_PLUGIN_ENOTSUP;
    g_app = &g_storage;
    G.host = host;
    G.lvgl = host->graphics.lvgl;
    /* Bluetooth is optional: without it the counter still works, just
     * without saved setups, stats or sound. */
    G.bt_available = host->bt_send != 0 &&
        (host->capabilities & GM_PLUGIN_CAP_BLUETOOTH) != 0U;
    if (gm_plugin_libc_get(host, &G.libc) != GM_PLUGIN_OK)
        return GM_PLUGIN_ENOTSUP;
    if (G.lvgl->struct_size < GM_PLUGIN_LVGL_API_MIN_SIZE ||
        !GM_PLUGIN_VERSION_COMPATIBLE(G.lvgl->api_version,
                                      GM_PLUGIN_LVGL_API_MIN_VERSION) ||
        G.lvgl->line_create == 0 || G.lvgl->line_set_points == 0)
        return GM_PLUGIN_EVERSION;
    /* Picture styles need LVGL 1.1 images; older firmware gets ring/stonks
     * and the live-drawn figures. */
    G.images_cap = host->alloc != 0 && host->free != 0 &&
        GM_PLUGIN_VERSION_COMPATIBLE(G.lvgl->api_version,
                                     GM_PLUGIN_VERSION(1U, 1U)) &&
        G.lvgl->struct_size >= GM_PLUGIN_LVGL_API_1_1_SIZE &&
        G.lvgl->image_create != 0 && G.lvgl->image_set_source != 0;
    plugin->abi_version = GM_PLUGIN_ABI_MIN_VERSION;
    G.call_ui.host = host;
    plugin->on_start = plugin_start;
    plugin->on_loop = plugin_loop;
    plugin->on_event = plugin_event;
    plugin->on_stop = plugin_stop;
    return GM_PLUGIN_OK;
}
