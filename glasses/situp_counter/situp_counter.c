    G.status_label = G.lvgl->label_create(root);
    G.info_label = G.lvgl->label_create(root);
    G.stats_label = G.lvgl->label_create(root);
    G.hint_label = G.lvgl->label_create(root);
    G.popup_label = G.lvgl->label_create(root);
    G.menu_box = G.lvgl->obj_create(root);
    G.shadow = G.lvgl->line_create(root);
