/*
 * Workout Counter - MemoMind glasses plugin (pairs with the Workout Tracker
 * phone plugin, but also runs on its own).
 *
 * Counts exercises that a sensor on your head can measure reliably:
 *   Sit-ups        big head tilt (start lying on your back)
 *   Toe & sky      tilt down to the toes, then up to the sky
 *   Jumping jacks  sharp landing jolts; setup learns how many make one jack
 *   Roll           a prank: looks like a workout, opens a "YOU GOT ROLLED!"
 *                  dance party (original art and music, all drawn live)
 * (Push-ups, squats and hip twists were dropped: the head barely tilts in a
 * push-up, stays level in a squat, and doesn't have to turn in a hip twist.
 * Their ids stay reserved so saved phone data still lines up.)
 *
 * Every exercise has a one-time setup (one slow rep, or three jacks) that
 * measures your own motion, so the raw sensor units never matter. The phone
 * stores those measurements, your history, high scores and streak, and plays
 * the sound effects (the glasses have no clock, storage or speaker).
 *
 * Controls
 *   Menu:     tilt your head up/down to move the highlight (or Up/Down),
 *             press to start, double press = re-centre, hold to exit
 *   Workout:  press = pause/resume (during setup: skip it), double press =
 *             back to the menu, hold = exit, Left/Right = animation style,
 *             Up/Down = fine-tune sensitivity
 *
 * Animation styles: 0 Ring, 1 Coach Head, 2 Stick Figure (default), 3 Glow-Up, 4 Aura,
 * 5 Judgy Cat, 6 Stonks. The sit-up art lives in sprites.h (generated by
 * tools/make_sprites.py); other exercises draw their figure live with lines.
 *
 * Sync protocol "fox89.situp-sync" 2.0, first byte = 2, little-endian:
 *   Glasses -> phone, channel 0x4648
 *     HELLO    [2, 1, exercise]
 *     SESSION  [2, 2, session u32, reps u16, seconds u16, exercise]   11 B
 *     STYLE    [2, 4, style]
 *     EVENT    [2, 5, event, style, value u16]   sound cue
 *              events: 1 ready, 2 rep, 3 new best, 4 pause, 5 resume, 6 tier
 *     CAL      [2, 6, exercise, a u16, b u16, c]   setup measured: save it
 *     EXERCISE [2, 9, exercise]   picked in the menu: send its stats
 *   Phone -> glasses, channel 0x4647
 *     STATS    [2, 3, best u16, best_year u16, best_month, best_day,
 *               streak u16, today u16, echo_session u32, echo_reps u16,
 *               style, exercise]                                     20 B
 *     SETUP    [2, 7, exercise]   run that exercise's setup again
 *     CALS     [2, 8, count, count x (a u16, b u16, c, valid)]   all saved
 *   The phone echoes the newest session it stored; the glasses resend
 *   SESSION until the echo matches, so a dropped message never loses reps.
 */
