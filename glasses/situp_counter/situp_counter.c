static bool handle_cals(const uint8_t *data, uint32_t length)
{
    uint32_t n, i;
    if (length < 3U) return false;
    n = data[2];
    for (i = 0U; i < n && i < EX_COUNT && 3U + i * 6U + 6U <= length; ++i) {
        const uint8_t *e = data + 3U + i * 6U;
        if (e[5] == 0U) continue;                       /* not set up yet */
        if (G.setup_forced && i == G.exercise) continue; /* recalibrating */
        G.cal[i].a = read_u16(e);
        G.cal[i].b = read_u16(e + 2);
        G.cal[i].c = e[4];
        G.cal[i].valid = 1U;
    }
    /* A saved setup arrived while setup was showing but untouched: skip it. */
    if (G.state == ST_SETUP && G.cal[G.exercise].valid &&
        G.setup_a == 0 && G.setup_b == 0 && G.setup_peaks == 0U)
        enter_ready();
    return true;
}

