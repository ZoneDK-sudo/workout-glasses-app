static bool handle_stats(const uint8_t *data, uint32_t length)
{
    uint8_t style;
    if (length < STATS_LENGTH) return false;
    style = usable_style(data[18]);
    if (G.style_pending) {
        if (style == G.style) G.style_pending = false;
    } else {
        select_style(style);
    }
    if (data[19] != G.exercise) return true;   /* stats for another exercise */
    G.best = read_u16(&data[2]);
    G.best_year = read_u16(&data[4]);
    G.best_month = data[6];
    G.best_day = data[7];
    G.streak = read_u16(&data[8]);
    G.today = read_u16(&data[10]);
    G.echo_session = read_u32(&data[12]);
    G.echo_reps = read_u16(&data[16]);
    G.have_stats = true;
    /* The phone already counts this session in "best"; only flash NEW BEST
     * when this session itself beat the previous record. */
    if (G.best > G.count) G.new_best_shown = false;
    return true;
}

