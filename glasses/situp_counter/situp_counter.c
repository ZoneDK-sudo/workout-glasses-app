{
    c->valid = 0U;
    c->b = 0U;
    c->c = 0U;
    switch (detector_of(ex)) {
    case DET_PITCH:        c->a = 50U; break;
    case DET_SIGNED_PITCH: c->a = 60U; c->b = 20U; break;
    default:               c->a = 1200U; c->c = 2U; break;
    }
}

