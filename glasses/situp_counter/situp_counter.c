static uint16_t rep_gain(uint32_t rep)
{
    return (uint16_t)(6U + (rep * 7U) % 11U);   /* 6..16, looks "market-y" */
}

static void close_price(void)
{
    uint16_t last = G.prices[G.price_count - 1U];
    uint16_t next = (uint16_t)(last + rep_gain(G.count));
    if (G.price_count == 8U) {
        G.libc->memmove(&G.prices[0], &G.prices[1], sizeof(G.prices[0]) * 7U);
        G.price_count--;
    }
    G.prices[G.price_count++] = next;
}

#define CHART_LEFT           70
#define CHART_TOP            62
#define CHART_W              230
#define CHART_H              140

static void update_chart(void)
{
    gm_plugin_lvgl_point_t *pts = G.chart_points[G.chart_buffer];
    uint16_t last = G.prices[G.price_count - 1U];
    int32_t live;
    int32_t lo = 0x7FFFFFFF;
    int32_t hi = 0;
    uint8_t n = (uint8_t)(G.price_count + 1U);
    uint8_t i;
    char text[40];

    /* The live point previews the next gain while you move, or crashes. */
    if (G.paused) live = last / 2;
    else if (G.state < ST_SETUP) live = last;
    else live = last + (int32_t)rep_gain(G.count + 1U) * clamp32(abs32(G.progress), 0, 1000) / 1000;
    for (i = 0U; i < G.price_count; ++i) {
        if (G.prices[i] < lo) lo = G.prices[i];
        if (G.prices[i] > hi) hi = G.prices[i];
    }
    if (live < lo) lo = live;
    if (live > hi) hi = live;
    if (hi - lo < 20) hi = lo + 20;
    for (i = 0U; i < n; ++i) {
        int32_t v = i < G.price_count ? G.prices[i] : live;
        pts[i].x = (gm_plugin_lvgl_coord_t)(CHART_LEFT + 6 + (int32_t)i * (CHART_W - 12) / 8);
        pts[i].y = (gm_plugin_lvgl_coord_t)(CHART_TOP + CHART_H - 6 - (v - lo) * (CHART_H - 16) / (hi - lo));
    }
    G.lvgl->line_set_points(G.chart_line, pts, n);
    G.chart_buffer ^= 1U;

    if (G.paused) G.libc->snprintf(text, sizeof(text), "NOT STONKS  $%d", (int)live);
    else if (G.new_best_flash_ms > 0U) G.libc->snprintf(text, sizeof(text), "TO THE MOON  $%d", (int)live);
    else if (G.happy_ms > 0U) G.libc->snprintf(text, sizeof(text), "STONKS  $%d", (int)live);
    else G.libc->snprintf(text, sizeof(text), "$GAINS  $%d", (int)live);
    G.lvgl->label_set_text(G.chart_label, text);
}
