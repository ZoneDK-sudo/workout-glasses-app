/* Sends 11 joint positions (screen coordinates) to the figure's lines:
 * spine, two legs, two arms and a 10-sided head. */
static void emit_figure(int32_t joint[JOINTS][2], bool glow)
{
    gm_plugin_lvgl_point_t (*pts)[FIG_PTS] = G.fig_points[G.fig_buffer];
    static const uint8_t chains[5][3] = {
        {1, 2, 2}, {2, 3, 4}, {2, 5, 6}, {1, 7, 8}, {1, 9, 10},
    };
    /* cos/sin x 1000 for 36-degree steps */
    static const int16_t ring[11][2] = {
        {1000,0},{809,588},{309,951},{-309,951},{-809,588},{-1000,0},
        {-809,-588},{-309,-951},{309,-951},{809,-588},{1000,0},
    };
    uint8_t line, k, n;
    for (line = 0; line < 5; ++line) {
        n = line == 0 ? 2U : 3U;
        for (k = 0; k < n; ++k) {
            pts[line][k].x = (gm_plugin_lvgl_coord_t)joint[chains[line][k]][0];
            pts[line][k].y = (gm_plugin_lvgl_coord_t)joint[chains[line][k]][1];
        }
        G.lvgl->line_set_points(G.fig[line], pts[line], n);
        if (glow) G.lvgl->line_set_points(G.fig_glow[line], pts[line], n);
    }
    for (k = 0; k < 11; ++k) {
        pts[5][k].x = (gm_plugin_lvgl_coord_t)(joint[0][0] + ring[k][0] * HEAD_R / 1000);
        pts[5][k].y = (gm_plugin_lvgl_coord_t)(joint[0][1] + ring[k][1] * HEAD_R / 1000);
    }
    G.lvgl->line_set_points(G.fig[5], pts[5], 11);
    if (glow) G.lvgl->line_set_points(G.fig_glow[5], pts[5], 11);
    G.fig_buffer ^= 1U;
}

/* Draws the exercise's stick figure at `pos` (-1000..1000; 0..1000 for
 * one-way exercises) by blending between its poses. */
static void draw_figure(uint8_t ex, int32_t pos, bool glow, int32_t x0)
{
    int32_t joint[JOINTS][2];
    uint8_t from, to;
    int32_t t;
    uint8_t j, k;
    bool two_way = detector_of(ex) == DET_SIGNED_PITCH;
    uint8_t row = pose_row(ex);

    if (two_way) {
        if (pos >= 0) { from = 1; to = 2; t = pos; }
        else { from = 1; to = 0; t = -pos; }
    } else {
        from = 0; to = 1; t = pos < 0 ? -pos : pos;
    }
    t = clamp32(t, 0, 1000);
    for (j = 0; j < JOINTS; ++j)
        for (k = 0; k < 2; ++k)
            joint[j][k] = (k ? FIG_Y0 : x0) + k_poses[row][from][j][k] +
                ((int32_t)(k_poses[row][to][j][k] - k_poses[row][from][j][k]) * t) / 1000;
    emit_figure(joint, glow);
}

/* sine x 1000 for 0..90 degrees in 6-degree steps (16 entries) */
static int32_t sin1000(int32_t deg)
{
    static const int16_t q[16] = { 0, 105, 208, 309, 407, 500, 588, 669, 743,
                                   809, 866, 914, 951, 978, 995, 1000 };
    int32_t d = ((deg % 360) + 360) % 360, s = 1, i;
    if (d >= 180) { d -= 180; s = -1; }
    if (d > 90) d = 180 - d;
    i = d / 6;
    return s * (i >= 15 ? 1000 : q[i] + (q[i + 1] - q[i]) * (d - i * 6) / 6);
}
static int32_t cos1000(int32_t deg) { return sin1000(deg + 90); }

/* Roll menu preview: a tucked stick man tumbling along the ground, left to
 * right, and back in from the left. */
static void draw_tumble(uint32_t ms, int32_t x0)
{
    int32_t joint[JOINTS][2];
    int32_t travel = (int32_t)(ms % 2400U) * 130 / 2400;   /* 0..130 px */
    int32_t cx = x0 + 10 + travel, cy = FIG_Y0 + 98;        /* ball centre */
    int32_t a = travel * 360 / 170;                          /* rolls, not slides */
    int32_t c = cos1000(a), s = sin1000(a);
    uint8_t j;
    for (j = 0; j < JOINTS; ++j) {
        int32_t dx = k_tuck[j][0] * 2, dy = k_tuck[j][1] * 2;   /* full size */
        joint[j][0] = cx + (dx * c - dy * s) / 1000;
        joint[j][1] = cy + (dx * s + dy * c) / 1000;
    }
    emit_figure(joint, false);
}

/* "YOU GOT ROLLED!": the dance, eased between moves on the beat. */
static void draw_dance(uint32_t ms, int32_t x0, int32_t y0)
{
    int32_t joint[JOINTS][2];
    uint32_t beat = ms / 500U;
    int32_t t = (int32_t)(ms % 500U) * 1000 / 500;
    int32_t bounce;
    const int8_t (*from)[2] = k_dance[k_dance_order[beat % 8U]];
    const int8_t (*to)[2] = k_dance[k_dance_order[(beat + 1U) % 8U]];
    uint8_t j;
    /* snap into each move quickly, then hold it (smug) */
    t = t < 350 ? t * 1000 / 350 : 1000;
    t = t * t / 1000 * (3000 - 2 * t) / 1000;        /* smoothstep */
    bounce = sin1000((int32_t)(ms % 500U) * 360 / 500) / 250;  /* knees on the beat */
    for (j = 0; j < JOINTS; ++j) {
        joint[j][0] = x0 + from[j][0] + (to[j][0] - from[j][0]) * t / 1000;
        joint[j][1] = y0 + from[j][1] + (to[j][1] - from[j][1]) * t / 1000;
        if (j != 4 && j != 6) joint[j][1] += bounce;   /* feet stay planted */
    }
    emit_figure(joint, false);
}

/* Spinning disco ball with flashing light rays, at (cx, cy). */
static void draw_disco(uint32_t ms, int32_t cx, int32_t cy)
{
    gm_plugin_lvgl_point_t (*pts)[11] = G.disco_points[G.disco_buffer];
    const int32_t r = 22;
    int32_t spin = (int32_t)(ms % 1000U) * 360 / 1000;
    uint8_t k, i;
    /* string */
    pts[0][0].x = (gm_plugin_lvgl_coord_t)cx; pts[0][0].y = 24;
    pts[0][1].x = (gm_plugin_lvgl_coord_t)cx; pts[0][1].y = (gm_plugin_lvgl_coord_t)(cy - r);
    G.lvgl->line_set_points(G.disco[0], pts[0], 2);
    /* ball outline */
    for (k = 0; k < 11; ++k) {
        pts[1][k].x = (gm_plugin_lvgl_coord_t)(cx + cos1000(k * 36) * r / 1000);
        pts[1][k].y = (gm_plugin_lvgl_coord_t)(cy + sin1000(k * 36) * r / 1000);
    }
    G.lvgl->line_set_points(G.disco[1], pts[1], 11);
    /* two facet "meridians" sliding across = spinning */
    for (i = 0; i < 2; ++i) {
        int32_t off = cos1000(spin + (int32_t)i * 90) * r / 1000;
        for (k = 0; k < 5; ++k) {
            int32_t ang = -90 + (int32_t)k * 45;
            pts[2 + i][k].x = (gm_plugin_lvgl_coord_t)(cx + off * cos1000(ang) / 1000);
            pts[2 + i][k].y = (gm_plugin_lvgl_coord_t)(cy + r * sin1000(ang) / 1000);
        }
        G.lvgl->line_set_points(G.disco[2 + i], pts[2 + i], 5);
    }
    /* equator band, bowed like the ball's surface */
    for (k = 0; k < 5; ++k) {
        int32_t ang = 180 + (int32_t)k * 45;
        pts[4][k].x = (gm_plugin_lvgl_coord_t)(cx + cos1000(ang) * r / 1000);
        pts[4][k].y = (gm_plugin_lvgl_coord_t)(cy + sin1000(ang) * r / 4000 + r / 6);
    }
    G.lvgl->line_set_points(G.disco[4], pts[4], 5);
    /* three light rays, flashing in turn on the beat */
    for (i = 1; i < 4; ++i) {
        int32_t ang = 20 + (int32_t)i * 40 + (int32_t)((ms / 500U) % 2U) * 15;
        bool on = ((ms / 250U) + i) % 3U != 0U;
        pts[4 + i][0].x = (gm_plugin_lvgl_coord_t)(cx + cos1000(ang) * (r + 6) / 1000);
        pts[4 + i][0].y = (gm_plugin_lvgl_coord_t)(cy + sin1000(ang) * (r + 6) / 1000);
        pts[4 + i][1].x = (gm_plugin_lvgl_coord_t)(cx + cos1000(ang) * (r + 30) / 1000);
        pts[4 + i][1].y = (gm_plugin_lvgl_coord_t)(cy + sin1000(ang) * (r + 30) / 1000);
        G.lvgl->line_set_points(G.disco[4 + i], pts[4 + i], 2);
        set_hidden(G.disco[4 + i], !on);
    }
    G.disco_buffer ^= 1U;
}

