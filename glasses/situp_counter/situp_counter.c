static uint32_t add_capped(uint32_t value, uint32_t delta, uint32_t cap)
{
    return (cap - value <= delta) ? cap : value + delta;
}

static uint32_t count_down(uint32_t value, uint32_t delta)
{
    return value > delta ? value - delta : 0U;
}

static int32_t abs32(int32_t v) { return v < 0 ? -v : v; }

static int32_t clamp32(int32_t v, int32_t lo, int32_t hi)
{
    return v < lo ? lo : v > hi ? hi : v;
}

static uint32_t isqrt32(uint32_t v)
{
    uint32_t r = 0U, bit = UINT32_C(1) << 30;
    while (bit > v) bit >>= 2;
    while (bit != 0U) {
        if (v >= r + bit) { v -= r + bit; r = (r >> 1) + bit; }
        else r >>= 1;
        bit >>= 2;
    }
    return r;
}

static uint16_t read_u16(const uint8_t *p)
{
    return (uint16_t)(p[0] | ((uint16_t)p[1] << 8));
}

static uint32_t read_u32(const uint8_t *p)
{
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8) |
           ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24);
}

static void write_u16(uint8_t *p, uint32_t v)
{
    p[0] = (uint8_t)v;
    p[1] = (uint8_t)(v >> 8);
}

static void write_u32(uint8_t *p, uint32_t v)
{
    p[0] = (uint8_t)v;
    p[1] = (uint8_t)(v >> 8);
    p[2] = (uint8_t)(v >> 16);
    p[3] = (uint8_t)(v >> 24);
}

